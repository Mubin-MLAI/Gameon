from datetime import datetime, time, timedelta
from decimal import Decimal

from django.core.management.base import BaseCommand
from django.db import transaction
from django.utils import timezone

from core.models import Booking, Customer, Facility, Payment

class Command(BaseCommand):
    help = "Create sample GameOn facilities and bookings for local development."

    def handle(self, *args, **options):
        samples = [
            ("Football Arena", Facility.Sport.FOOTBALL, Decimal("3000.00"), "A full-size, floodlit pitch for your next match."),
            ("Cricket Ground", Facility.Sport.CRICKET, Decimal("2500.00"), "A versatile ground for practice and match days."),
            ("Cricket Nets", Facility.Sport.NETS, Decimal("800.00"), "Focused net sessions for every level of batter."),
        ]
        for name, sport, hourly_rate, description in samples:
            Facility.objects.update_or_create(
                name=name,
                defaults={"sport": sport, "hourly_rate": hourly_rate, "description": description, "is_active": True},
            )

        demo_bookings = [
            {
                "mobile": "0000000101",
                "name": "Demo Customer - Alex Morgan",
                "email": "alex.morgan@example.invalid",
                "facility": "Football Arena",
                "day_offset": 1,
                "start_hour": 10,
                "source": Booking.Source.OFFLINE,
                "advance": Decimal("500.00"),
                "method": Booking.PaymentMethod.CASH,
            },
            {
                "mobile": "0000000102",
                "name": "Demo Customer - Jamie Patel",
                "email": "jamie.patel@example.invalid",
                "facility": "Cricket Ground",
                "day_offset": 2,
                "start_hour": 14,
                "source": Booking.Source.ONLINE,
                "advance": Decimal("0.00"),
                "method": "",
            },
            {
                "mobile": "0000000103",
                "name": "Demo Customer - Taylor Singh",
                "email": "taylor.singh@example.invalid",
                "facility": "Cricket Nets",
                "day_offset": 3,
                "start_hour": 18,
                "source": Booking.Source.OFFLINE,
                "advance": Decimal("200.00"),
                "method": Booking.PaymentMethod.UPI,
            },
        ]
        created = 0
        with transaction.atomic():
            for sample in demo_bookings:
                facility = Facility.objects.get(name=sample["facility"], is_active=True)
                customer, _ = Customer.objects.get_or_create(
                    mobile=sample["mobile"],
                    defaults={
                        "name": sample["name"],
                        "email": sample["email"],
                        "notes": "DEMO DATA - generated by seed_demo; not a real customer.",
                    },
                )
                customer.name = sample["name"]
                customer.email = sample["email"]
                customer.notes = "DEMO DATA - generated by seed_demo; not a real customer."
                customer.save(update_fields=["name", "email", "notes"])

                booking_date = timezone.localdate() + timedelta(days=sample["day_offset"])
                start_at = timezone.make_aware(
                    datetime.combine(booking_date, time(sample["start_hour"], 0)),
                    timezone.get_current_timezone(),
                )
                booking, was_created = Booking.objects.get_or_create(
                    customer=customer,
                    facility=facility,
                    start_at=start_at,
                    defaults={
                        "end_at": start_at + timedelta(hours=1),
                        "source": sample["source"],
                        "status": Booking.Status.CONFIRMED,
                        "total_amount": facility.hourly_rate,
                        "advance_paid": sample["advance"],
                        "payment_method": sample["method"],
                        "payment_reference": "DEMO-SEED" if sample["advance"] else "",
                        "notes": "DEMO DATA - generated by seed_demo; not a real booking.",
                    },
                )
                if was_created:
                    created += 1
                    if sample["advance"]:
                        Payment.objects.get_or_create(
                            booking=booking,
                            reference="DEMO-SEED",
                            defaults={
                                "customer": customer,
                                "amount": sample["advance"],
                                "method": sample["method"],
                            },
                        )

        self.stdout.write(self.style.SUCCESS(
            f"Ready: {len(samples)} demo facilities; {created} demo bookings added. "
            "Re-running this command will not duplicate the sample bookings."
        ))